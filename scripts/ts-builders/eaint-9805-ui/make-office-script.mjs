// Writes an Office Script (TypeScript) that builds the "UI TS" tab inside
// Excel Online from ui-rows.json — used when the file is locked for shared
// use and cannot be replaced (Hui Xin had it open, 2026-11-03). Text goes in
// plain; the bold / colour runs are applied afterwards (see README).
import fs from "node:fs";
const SPEC = JSON.parse(fs.readFileSync(new URL("./ui-rows.json", import.meta.url), "utf8"));
const strip = s => s.replace(/\*\*|\+\+|!!/g, "");
const nl = s => (s.endsWith("\n") ? s : s + "\n");
const per = w => Math.floor(w * 1.15);
const lines = (t, w) => t.split("\n").reduce((n, l) => n + Math.max(1, Math.ceil(l.length / per(w))), 0);
const rows = []; let n = 0;
for (const sec of SPEC.sections) {
  rows.push({ band: sec.title });
  for (const r of sec.rows) {
    n++;
    const open = SPEC.sets[r.dev ?? sec.dev];
    const t = [nl(strip(r.obj)), nl(strip(r.steps)), nl(strip(r.exp))];
    const rem = r.rem ? nl(r.rem) : "";
    const h = Math.max(lines(t[0], 34), lines(t[1], 40), lines(t[2], 46), rem ? lines(rem, 30) : 1) * 15;
    rows.push({ id: `9805_UI_TS${String(n).padStart(2, "0")}`, p: r.p, c: t[0], d: t[1], e: t[2], g: rem, open: SPEC.columns.map(c => open.includes(c)), h });
  }
}
const script = `// EAINT-9805: build the "UI TS" tab (generated by scripts/ts-builders/eaint-9805-ui/make-office-script.mjs).
function main(workbook: ExcelScript.Workbook) {
  const NAME = "UI TS";
  const tpl = workbook.getWorksheets().find(w => w.getName().indexOf("Performance") >= 0);
  if (!tpl) { console.log("Device & Performance TS not found - stopped"); return; }
  const old = workbook.getWorksheet(NAME);
  if (old) {
    if (old.getUsedRange(true)) { console.log("UI TS already has content - stopped"); return; }
    old.delete(); // empty tab left by a failed run
  }
  const ws = workbook.addWorksheet(NAME);
  const COLS: string[] = ${JSON.stringify(SPEC.columns)};
  const ROWS: { band?: string; id?: string; p?: string; c?: string; d?: string; e?: string; g?: string; open?: boolean[]; h?: number }[] = ${JSON.stringify(rows)};
  const L = "ABCDEFGHIJKLM";
  const last = L[6 + COLS.length];
  [14, 10, 34, 40, 46, 12, 30].forEach((w, i) => ws.getRange(L[i] + ":" + L[i]).getFormat().setColumnWidth(tpl.getRange(L[i] + ":" + L[i]).getFormat().getColumnWidth()));
  for (let i = 0; i < COLS.length; i++) ws.getRange(L[7 + i] + ":" + L[7 + i]).getFormat().setColumnWidth(tpl.getRange("H:H").getFormat().getColumnWidth());

  ws.getRange("A1:" + last + "1").copyFrom(tpl.getRange("A1"), ExcelScript.RangeCopyType.formats);
  ws.getRange("A1").setValue(tpl.getRange("A1").getValue());
  ws.getRange("A1:" + last + "1").merge(false);

  ws.getRange("A2:G2").copyFrom(tpl.getRange("A2:G2"), ExcelScript.RangeCopyType.all);
  COLS.forEach((h, i) => {
    const c = ws.getRange(L[7 + i] + "2");
    c.copyFrom(tpl.getRange(/^(iOS|iPadOS)/.test(h) ? "L2" : "H2"), ExcelScript.RangeCopyType.formats);
    c.setValue(h);
  });

  let r = 3;
  for (const row of ROWS) {
    if (row.band) {
      ws.getRange("A" + r + ":" + last + r).copyFrom(tpl.getRange("A3"), ExcelScript.RangeCopyType.formats);
      ws.getRange("A" + r).setValue(row.band);
      ws.getRange("A" + r + ":" + last + r).merge(false);
    } else {
      ws.getRange("A" + r + ":G" + r).copyFrom(tpl.getRange("A4:G4"), ExcelScript.RangeCopyType.all);
      ws.getRange("A" + r + ":G" + r).setValues([[row.id, row.p, row.c, row.d, row.e, "", row.g]]);
      row.open.forEach((o, i) => {
        const c = ws.getRange(L[7 + i] + r);
        if (o) { c.copyFrom(tpl.getRange("H4"), ExcelScript.RangeCopyType.all); c.setValue("Not Started"); }
        else { c.copyFrom(tpl.getRange("I4"), ExcelScript.RangeCopyType.all); c.getDataValidation().clear(); c.setValue(""); }
      });
      ws.getRange("A" + r).getFormat().setRowHeight(row.h);
    }
    r++;
  }
  console.log("UI TS built: rows 3-" + (r - 1));
}
`;
fs.writeFileSync(process.argv[2], script);
console.log("rows", rows.length, "bytes", script.length);
